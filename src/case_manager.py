import yaml
import os
import time
import uuid
from sqlalchemy.orm import Session
from database.models import FraudCase, CaseHistory
import logging

logger = logging.getLogger(__name__)

CONFIG_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), '../config/alert_policy.yaml'))

class CaseManager:
    def __init__(self):
        self._load_config()

    def _load_config(self):
        with open(CONFIG_PATH, 'r') as file:
            self.config = yaml.safe_load(file)
            self.alert_mapping = self.config['alert_mapping']
            self.dedup_enabled = self.config['deduplication']['enabled']
            self.fallback_dedup = self.config['deduplication']['fallback_to_audit_id']

    def evaluate_and_create_case(self, transaction_data: dict, decision_data: dict, audit_log_id: int, db: Session):
        """
        Evaluates the decision against the alert policy and creates a FraudCase if required.
        Safely handles deduplication.
        """
        try:
            recommended_action = decision_data.get("recommended_action", "APPROVE")
            policy = self.alert_mapping.get(recommended_action, self.alert_mapping["APPROVE"])
            
            if not policy.get("create_case", False):
                return None # No case needed
                
            transaction_id = transaction_data.get("transaction_id", "TX_000")
            
            # Phase 6: Case Deduplication
            if self.dedup_enabled:
                if transaction_id != "TX_000":
                    existing = db.query(FraudCase).filter(FraudCase.transaction_id == transaction_id).first()
                    if existing:
                        logger.warning(f"Duplicate case skipped for transaction: {transaction_id}")
                        return existing.id
                elif self.fallback_dedup:
                    existing = db.query(FraudCase).filter(FraudCase.audit_log_id == audit_log_id).first()
                    if existing:
                        return existing.id
            
            # Phase 5: Automatic Case Creation
            case_id = f"CASE_{uuid.uuid4().hex[:8].upper()}"
            
            new_case = FraudCase(
                id=case_id,
                transaction_id=transaction_id,
                audit_log_id=audit_log_id,
                severity=policy.get("severity", "LOW"),
                status="OPEN",
                fraud_probability=decision_data.get("fraud_probability", 0.0),
                decision=recommended_action,
                decision_confidence=decision_data.get("decision_confidence", "UNKNOWN")
            )
            
            history_entry = CaseHistory(
                case_id=case_id,
                action="CASE_CREATED",
                new_status="OPEN",
                notes=f"Auto-generated by {recommended_action} decision."
            )
            
            db.add(new_case)
            db.add(history_entry)
            db.commit()
            
            return case_id
            
        except Exception as e:
            # Important: Prediction must succeed even if case creation fails
            logger.error(f"Failed to create fraud case: {str(e)}")
            db.rollback()
            return None

# Global instance
case_manager = CaseManager()
